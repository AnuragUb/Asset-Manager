const TABLES = ['asset_folders', 'asset_history', 'asset_it_details', 'asset_hierarchy'];

async function columnList(knex, schema, table) {
  const rows = await knex('information_schema.columns')
    .where({ table_schema: schema, table_name: table })
    .orderBy('ordinal_position')
    .pluck('column_name');
  return rows.map((name) => `"${name}"`).join(', ');
}

async function assertSameRows(knex, table) {
  const cols = await columnList(knex, 'public', table);
  const diff = await knex.raw(`
    SELECT (
      (SELECT count(*) FROM (SELECT ${cols} FROM public.${table} EXCEPT SELECT ${cols} FROM assets.${table}) d)
      + (SELECT count(*) FROM (SELECT ${cols} FROM assets.${table} EXCEPT SELECT ${cols} FROM public.${table}) d)
    )::int AS n
  `);
  if (diff.rows[0].n) {
    throw new Error(`STOP: ${table} rows differ between public and assets`);
  }
}

