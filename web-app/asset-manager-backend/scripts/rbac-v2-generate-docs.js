/**
 * Generate RBAC_PERMISSION_MATRIX.md + RBAC_ROUTE_COVERAGE.md from catalog + route inventory.
 * Run: docker run --rm -v ... node:20 node scripts/rbac-v2-generate-docs.js
 */
const fs = require('fs');
const path = require('path');
const {
  NEW_PERMISSIONS,
  VIEW_ALIASES,
  ROLE_ACTION_GRANTS,
  LOGISTICS_ACTIONS
} = require('../services/permissionCatalog');

const root = path.join(__dirname, '../../..');
const docsDir = path.join(root, 'docs');
const inventoryPath = path.join(__dirname, '../rbac-v2-route-inventory.json');

// Re-enumerate inline if inventory missing
function enumerate() {
  const t = fs.readFileSync(path.join(__dirname, '../server.js'), 'utf8');
  const lines = t.split(/\n/);
  const rows = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const m = line.match(/app\.(get|post|put|patch|delete)\(\s*['"]([^'"]+)['"]/);
    if (!m) continue;
    const method = m[1].toUpperCase();
    const route = m[2];
    if (!route.startsWith('/api/')) continue;
    const hasAuth = /authenticateJWT/.test(line);
    const reqMatch = line.match(/requirePermission\s*\(\s*['"]([^'"]+)['"]\s*\)/);
    const hasRoles = /authorizeRoles/.test(line);
    rows.push({
      line: i + 1,
      method,
      route,
      hasAuth,
      hasReq: !!reqMatch,
      permission: reqMatch ? reqMatch[1] : '',
      hasRoles,
      isMutation: ['POST', 'PUT', 'PATCH', 'DELETE'].includes(method)
    });
  }
  return rows;
}

const rows = enumerate();
const mutations = rows.filter((r) => r.isMutation);

function resourceAction(perm) {
  if (!perm) return { resource: '', action: '' };
  const i = perm.lastIndexOf('.');
  if (i < 0) return { resource: perm, action: '' };
  return { resource: perm.slice(0, i), action: perm.slice(i + 1) };
}

const coverageLines = [
  '# RBAC Route Coverage',
  '',
  'Generated by `scripts/rbac-v2-generate-docs.js` during RBAC V2 hardening.',
  '',
  'Rule: every state-changing API must use `requirePermission(<action>)`.',
  'Frontend checks are UX only.',
  '',
  '| HTTP | ROUTE | RESOURCE | ACTION | REQUIRED PERMISSION | CURRENT CHECK | STATUS |',
  '|------|-------|----------|--------|---------------------|---------------|--------|'
];

for (const r of mutations) {
  const { resource, action } = resourceAction(r.permission);
  let status = 'ok';
  let check = r.permission ? `requirePermission('${r.permission}')` : 'none';
  if (r.hasRoles && r.hasReq) check += ' + authorizeRoles';
  if (r.hasRoles && !r.hasReq) {
    status = 'roles-only';
    check = 'authorizeRoles only';
  } else if (r.hasAuth && !r.hasReq && !r.hasRoles) {
    status = 'auth-only';
    check = 'authenticateJWT only';
  } else if (!r.hasAuth && !r.hasReq) {
    // Classify known intentional public / disabled / service-portal
    if (/^\/api\/auth\//.test(r.route) || r.route === '/api/signup') status = 'public-auth';
    else if (/^\/api\/ocr\//.test(r.route)) status = 'gap-ocr-unauthed';
    else if (/^\/api\/arri\//.test(r.route) || /^\/api\/service\//.test(r.route)) status = 'gap-service-portal';
    else if (/^\/api\/icons\//.test(r.route) || r.route === '/api/upload-logo' || /upload-image/.test(r.route)) status = 'gap-upload-unauthed';
    else if (r.route === '/api/tally/sync') status = 'gap-tally-unauthed';
    else if (/^\/api\/quotas/.test(r.route)) status = 'gap-quotas-unauthed';
    else if (/^\/api\/dynamic/.test(r.route)) status = 'gap-dynamic-unauthed';
    else if (/^\/api\/external\//.test(r.route)) status = 'gap-external-unauthed';
    else if (r.route === '/api/quantity/split') status = 'disabled-410';
    else status = 'bare-unauthed';
    check = 'none';
  } else if (r.hasReq && (/\.view$/.test(r.permission) || /^view\./.test(r.permission))) {
    status = 'view-as-mutation';
  }
  coverageLines.push(
    `| ${r.method} | \`${r.route}\` | ${resource || '—'} | ${action || '—'} | ${r.permission || '—'} | ${check} | ${status} |`
  );
}

const summary = {
  mutations: mutations.length,
  protected: mutations.filter((r) => r.hasReq).length,
  rolesOnly: mutations.filter((r) => r.hasRoles && !r.hasReq).length,
  authOnly: mutations.filter((r) => r.hasAuth && !r.hasReq && !r.hasRoles).length,
  bare: mutations.filter((r) => !r.hasAuth && !r.hasReq).length
};

coverageLines.push(
  '',
  '## Summary',
  '',
  `- Mutation routes: **${summary.mutations}**`,
  `- With requirePermission: **${summary.protected}**`,
  `- authorizeRoles only: **${summary.rolesOnly}**`,
  `- authenticateJWT only: **${summary.authOnly}**`,
  `- No auth middleware: **${summary.bare}** (see STATUS column for classification)`,
  '',
  '## Intentional / deferred gaps',
  '',
  '- Auth login/logout/forgot/reset/signup — public by design',
  '- OCR / Arri / service portal mutations — separate auth boundary (documented gap; not expanded in V2)',
  '- Icon/logo uploads, tally sync, quotas, dynamic forms, external project hooks — pre-existing unauthenticated surfaces; tracked as unresolved authorization gaps',
  '- `POST /api/quantity/split` — disabled (410); use `/api/break`',
  '',
  '## Role-name bypasses',
  '',
  '- Backend `hasPermission`: **superuser-only** centralized bypass',
  '- Frontend `hasPermission` / `can()`: **superuser-only** centralized bypass',
  '- Admin: stored `role_permissions` only (no FE/BE role-name allow-all)'
);

const matrixLines = [
  '# RBAC Permission Matrix (V2)',
  '',
  'Canonical model: `module.*.access` → workspace · `resource.view` → read · `resource.action` → mutation.',
  '',
  'Scratch verification DB: `asset_manager_rbac_scratch` (prod untouched).',
  '',
  '## Legacy → canonical view mapping',
  '',
  '| Legacy | Canonical |',
  '|--------|-----------|'
];
for (const [legacy, canon] of Object.entries(VIEW_ALIASES)) {
  matrixLines.push(`| \`${legacy}\` | \`${canon}\` |`);
}

matrixLines.push(
  '',
  '## New / action catalog entries',
  '',
  '| Key | Category | Description |',
  '|-----|----------|-------------|'
);
for (const p of NEW_PERMISSIONS) {
  matrixLines.push(`| \`${p.key}\` | ${p.category} | ${p.description} |`);
}

matrixLines.push(
  '',
  '## Role action grants (beyond migrated views)',
  '',
  '| Role | Action keys (count) | Notes |',
  '|------|---------------------|-------|'
);

for (const [role, keys] of Object.entries(ROLE_ACTION_GRANTS)) {
  matrixLines.push(
    `| ${role} | ${keys.length} | ${keys.length ? keys.slice(0, 8).map((k) => '`' + k + '`').join(', ') + (keys.length > 8 ? ', …' : '') : '_views only_'} |`
  );
}

matrixLines.push(
  '',
  '## Logistics action bundle',
  '',
  'Granted to `superuser`, `admin`, and (minus `manage.hierarchy`) `manager`:',
  '',
  LOGISTICS_ACTIONS.map((k) => `- \`${k}\``).join('\n'),
  '',
  '## Privilege preservation rules',
  '',
  '- Logistics Executive / user / client: **no** mutation action grants',
  '- IT roles: network + asset search; no procurement/DC/RN mutations',
  '- HR: `user.manage` + settings view; no physical mutations',
  '- `manage.hierarchy`: stored for admin + superuser only',
  '- `category.delete`: remains admin/superuser via grants (superuser also has global bypass)',
  '',
  '## Deprecated (kept for dual-resolve)',
  '',
  'All legacy `view.*` keys remain in catalog with category `deprecated` until a later named migration removes them after zero code references.',
  ''
);

const outDocs = path.join(__dirname, '..'); // write beside backend; host copies to docs/
fs.writeFileSync(path.join(outDocs, 'RBAC_ROUTE_COVERAGE.md'), coverageLines.join('\n') + '\n');
fs.writeFileSync(path.join(outDocs, 'RBAC_PERMISSION_MATRIX.md'), matrixLines.join('\n'));
fs.writeFileSync(
  path.join(__dirname, '../rbac-v2-route-inventory.json'),
  JSON.stringify({ generatedAt: new Date().toISOString(), summary, rows, mutations }, null, 2)
);
console.log(JSON.stringify({ out: outDocs, summary }, null, 2));
